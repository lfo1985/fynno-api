package br.api.fynno.model.entity;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;

import java.time.LocalDateTime;

// Utiliza-se a anotação Entity para indicar ao
// jpa que classe User é classe de entidade
// e o modelo da tabela e usar a anotação Table
// define a qual tabela pertence este modelo de
// entidade; no nosso caso esta anotação se faz
// necessária porque o nome da tabela é diferente
// do nome da entidade.
// --------------------------------------------
// A anotação Column indica que as propriedades
// representam as colunas da entidade que será
// mapeada com o banco de dados. os nomes não
// são necessários dentro do parâmetro do Column,
// mas vamos fazer de maneira que guardemos esta
// função, porque caso o nome da coluna seja diferente
// do que tá criado na entidade, podemos setar o nome
// da coluna através do parâmetro e associar à propriedade.
// --------------------------------------------
// A anotação Id indica qual é a coluna de identificação
// única (chave primária) da tabela para o modelo da
// entidade.
// --------------------------------------------
// Para funcionar o auto_increment semelhante ao mysql
// para o H2 é aplicado no campo dentro da schema o comando
// GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, isso seta
// para a base de dados que a tabela vai receber o ID como
// auto_increment, mas é preciso também informar à entidade
// que o registro dela no banco será desta maneira, portanto
// se deve usar GeneratedValue, cujo parâmetro é a constante
// IDENTITY de GenerationType. Implementando esta anotação
// configuramos ao spring que este Id vai receber dados
// auto_increment.
@Entity
@Table(name = "users")
public class User {
    // As notações Getters e Setters apontam ao lombok
    // que durante a compilação dele deve criar automaticamente
    // os getters e setters destas propriedades, sendo assim
    // não é necessário implemetá-los na entidade.

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", unique = true)
    @Getter
    private Integer id;

    @Getter
    @Setter
    @Column(name = "name", nullable = false)
    private String name;

    @Getter
    @Setter
    @Column(name = "email", nullable = false)
    private String email;

    @Column(name = "password_hash", nullable = false)
    private String password_hash;

    @Getter
    @Setter
    @Column(name = "active")
    private Boolean active;

    @Column(name = "created_at")
    private LocalDateTime created_at;

    @Column(name = "updated_at")
    private LocalDateTime updated_at;

    public void setPasswordHash(String password_hash) {
        this.password_hash = password_hash;
    }

    // Neste caso eu criei os dois getters porque existe
    // o underline e o método viria com nomenclatura errada
    // se colocasse o "lobok", ficaria getCreated_at, e isso
    // iria ferir o meu padrão camelCase de nomenclatura.
    public LocalDateTime getCreatedAt() {
        return created_at;
    }

    // Idem o item de cima.
    public LocalDateTime getUpdatedAt() {
        return updated_at;
    }

    // Usar as notações @PrePersist e @PreUpdate
    // são dois gatilhos durante a execução da transaction.
    // PrePersist prepara alguns dados antes da inserção
    // das informações da entidade na base.
    // ----------------------------------------------------------
    // PreUpdate prepara os dados antes da atualização do registro
    // na base de dados.
    // ----------------------------------------------------------
    // Neste caso seta as datas de criação, atualização e o active
    // para criar o registro.
    @PrePersist
    private void beforeInsert() {
        LocalDateTime now = LocalDateTime.now();
        this.created_at = now;
        this.updated_at = now;
        this.active = true;
    }

    // Neste caso seta para o update_at a data de atualização.
    @PreUpdate
    private void beforeUpdate() {
        this.updated_at = LocalDateTime.now();
    }

    @Override
    public String toString() {
        return "User{" +
                "id=" + id +
                ", name='" + name + '\'' +
                ", email='" + email + '\'' +
                ", password_hash='" + password_hash + '\'' +
                ", active=" + active +
                ", created_at='" + created_at + '\'' +
                ", updated_at='" + updated_at + '\'' +
                '}';
    }
}
